# Estudo da estrutura de repetição while (Enquanto)
# Útil quando não se sabem o número de iterações que o laço terá.
# Iteração é cada vez que o while for executado.

# Solicitar números ao usuário até que ele digite um número maior que 100
numero = 0

while numero <= 100:
    numero = int(input("Digite um número: "))
