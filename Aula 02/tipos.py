# Exemplos de tipagem de variáveis em Python

#Tipos de dados básicos (treino)
idade = 25 #inteiro
altura = 1.75 #real
nome = "João" #string
is_estudante = True #lógico

# Verificando os tipos de variáveis com o type()
print(type(idade))
print(type(altura))
print(type(nome))
print(type(is_estudante))
# É uma função importante para testes durante uma depuração, por exemplo.