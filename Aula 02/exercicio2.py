# Exercício de Fixação 2 
# Variáveis

numero1 = "7"
numero2 = "53" # atribuindo string às variáveis

print(type(numero1))
print(type(numero2)) # verificando o tipo

numero1_int = int(numero1)
numero2_int = int(numero2) # usando a função interna para realizar a alteração e a multiplicação

resultado = numero1_int * numero2_int
# criação de nova variável e atribuindo operação de multiplicação
print(resultado)
# exibe o resultado